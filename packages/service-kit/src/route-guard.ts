import type { FastifyInstance, RouteOptions } from 'fastify';

export class RouteDeclarationError extends Error {
  constructor(method: string, url: string, key: string) {
    super(`Route ${method} ${url} has no config.${key} declaration (spec 2.5: deny by default).`);
    this.name = 'RouteDeclarationError';
  }
}

/**
 * Spec 2.5 / 10.4: every route must declare its policy. Registering a route without
 * `config[key]` throws during startup, so the service cannot boot and tests fail in CI.
 *
 * Must be called before any route is registered.
 */
export function enforceRouteDeclarations(
  app: FastifyInstance,
  key: string,
  isValid: (value: unknown) => boolean,
): void {
  app.addHook('onRoute', (route: RouteOptions) => {
    // HEAD routes are auto-generated by Fastify from GET routes and share their config.
    const config = route.config as Record<string, unknown> | undefined;
    const value = config ? Object.entries(config).find(([k]) => k === key)?.[1] : undefined;
    if (!isValid(value)) {
      const method = Array.isArray(route.method) ? route.method.join(',') : route.method;
      throw new RouteDeclarationError(method, route.url, key);
    }
  });
}
